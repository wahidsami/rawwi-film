import type { BenchmarkCase } from "./benchmarkTypes.js";

function glossary(title: string, entries: BenchmarkCase["glossary"]["entries"]): BenchmarkCase["glossary"] {
  return Object.freeze({
    title,
    entries: Object.freeze(entries),
    notes: Object.freeze([]),
  });
}

function subjectModule(id: string, titleAr: string): BenchmarkCase["subjectModule"] {
  return Object.freeze({
    id,
    titleAr,
    scope: `${titleAr} benchmark case`,
    rules: Object.freeze([]),
    exclusions: Object.freeze([]),
    requiredEvidence: Object.freeze([]),
    decisionTree: Object.freeze([]),
    examples: Object.freeze([]),
    nonExamples: Object.freeze([]),
    articleIds: Object.freeze([]),
    notes: Object.freeze([]),
  });
}

function assessment(
  narrativeUnderstanding: string,
  speaker: string | null,
  target: string | null,
  victim: string | null,
  narrativeIntent: string,
  evidenceStrength: number,
  contextClassification: string,
  literalVsImpliedMeaning: string,
  exceptionSignals: readonly string[],
): BenchmarkCase["expectedReviewerAssessment"] {
  return Object.freeze({
    narrativeUnderstanding,
    speaker,
    target,
    victim,
    narrativeIntent,
    evidenceStrength,
    contextClassification,
    literalVsImpliedMeaning,
    exceptionSignals: Object.freeze([...exceptionSignals]),
  });
}

function finding(moduleId: string, disposition: BenchmarkCase["expectedFinding"]["disposition"], articleIds: readonly number[], conceptIds: readonly string[]): BenchmarkCase["expectedFinding"] {
  const articlesText = articleIds.length > 0 ? articleIds.join(",") : "none";
  const conceptsText = conceptIds.length > 0 ? conceptIds.join(",") : "none";
  return Object.freeze({
    disposition,
    summary: `module=${moduleId} | disposition=${disposition} | articles=${articlesText} | concepts=${conceptsText}`,
  });
}

function explanation(moduleId: string, disposition: BenchmarkCase["expectedFinding"]["disposition"], conceptIds: readonly string[], intent: string, context: string, exceptions: readonly string[], articleIds: readonly number[]): string {
  return [
    `module=${moduleId}`,
    `concepts=${conceptIds.length > 0 ? conceptIds.join(",") : "none"}`,
    `intent=${intent}`,
    `context=${context}`,
    `exceptions=${exceptions.length > 0 ? exceptions.join(",") : "none"}`,
    `articles=${articleIds.length > 0 ? articleIds.join(",") : "none"}`,
    `disposition=${disposition}`,
  ].join(" | ");
}

function makeCase(input: {
  id: string;
  title: string;
  snippet: string;
  storyMemory?: string | null;
  sceneMemory?: string | null;
  neighboringSentences?: readonly string[];
  glossary: BenchmarkCase["glossary"];
  subjectModule: BenchmarkCase["subjectModule"];
  expectedConcepts: readonly string[];
  expectedReviewerAssessment: BenchmarkCase["expectedReviewerAssessment"];
  expectedLegalModule: string;
  expectedArticleMapping: readonly number[];
  expectedFindingDisposition: BenchmarkCase["expectedFinding"]["disposition"];
  expectedConfidenceRange: BenchmarkCase["expectedConfidenceRange"];
}): BenchmarkCase {
  const expectedArticleMapping = Object.freeze([...input.expectedArticleMapping]);
  const expectedConcepts = Object.freeze([...input.expectedConcepts]);
  const expectedFinding = finding(input.expectedLegalModule, input.expectedFindingDisposition, expectedArticleMapping, expectedConcepts);
  return Object.freeze({
    id: input.id,
    title: input.title,
    scriptSnippet: input.snippet,
    storyMemory: input.storyMemory ?? null,
    sceneMemory: input.sceneMemory ?? null,
    neighboringSentences: Object.freeze([...(input.neighboringSentences ?? [])]),
    glossary: input.glossary,
    subjectModule: input.subjectModule,
    expectedConcepts,
    expectedReviewerAssessment: input.expectedReviewerAssessment,
    expectedLegalModule: input.expectedLegalModule,
    expectedArticleMapping,
    expectedFinding,
    expectedExplanation: explanation(
      input.expectedLegalModule,
      input.expectedFindingDisposition,
      expectedConcepts,
      input.expectedReviewerAssessment.narrativeIntent,
      input.expectedReviewerAssessment.contextClassification,
      input.expectedReviewerAssessment.exceptionSignals,
      expectedArticleMapping,
    ),
    expectedConfidenceRange: input.expectedConfidenceRange,
  });
}

